package model;

/**
 * Варианты отделки квартиры.
 */
public enum Furnish {
    /**
     * Дизайнерская отделка.
     */
    DESIGNER,

    /**
     * Отделки нет.
     */
    NONE,

    /**
     * Хорошая отделка.
     */
    FINE,

    /**
     * Плохая отделка.
     */
    BAD,

    /**
     * Минимальная отделка.
     */
    LITTLE
}
